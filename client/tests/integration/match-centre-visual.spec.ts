import { expect, test } from '@playwright/test'

test('visual-first layout keeps the match near the top and details keyboard-reachable without losing evidence', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByTestId('scoreline')).toHaveText('0 – 0')

  const frame = await page.getByRole('figure', { name: 'Broadcast frame with synthetic event map' }).boundingBox()
  const pitch = await page.getByRole('img', { name: /Event map of the last/ }).boundingBox()
  const mobile = (page.viewportSize()?.width ?? 1280) < 600
  expect(frame).not.toBeNull()
  expect(pitch).not.toBeNull()
  expect(frame!.y).toBeLessThan(mobile ? 700 : 450)
  expect(pitch!.y).toBeLessThan(mobile ? 780 : 550)
  await expect(page.getByLabel('Favourite club')).toBeHidden()
  await expect(page.getByRole('radio', { name: 'Operator-gated', exact: true })).toBeHidden()
  await expect(page.getByText('Curated replay · rules only · no approval', { exact: true })).toBeVisible()

  const personalise = page.locator('.mc-preferences > summary')
  await personalise.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Favourite club')).toBeVisible()
  await page.getByLabel('Favourite club').selectOption('LANTERNS')
  await expect(page.getByLabel('Follow a player')).toHaveValue('LANTERNS-09')
  await personalise.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Favourite club')).toBeHidden()
  await expect(page.getByRole('heading', { name: '#9 Zane Ostrander' })).toBeVisible()

  const options = page.getByText('Playback options & guide', { exact: true })
  await options.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('radio', { name: 'Operator-gated', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Incremental live simulation' })).toBeVisible()
  await options.focus()
  await page.keyboard.press('Enter')

  await page.getByLabel('Speed').selectOption('30')
  await page.getByRole('button', { name: 'Kick off', exact: true }).click()
  await expect(page.locator('.mc-ball-pulse')).toHaveCSS('animation-name', 'none')
  await expect(page.locator('.mc-new-action')).toHaveCSS('animation-name', 'none')
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  await page.getByRole('button', { name: 'Full-time recap', exact: true }).click()
  await expect(page.getByTestId('match-status')).toContainText('Full time')
  await expect(page.locator('[data-testid="moment-card"]:visible')).toHaveCount(6)
  await expect(page.locator('.mc-player-numbers > div')).toHaveCount(3)
  await expect(page.locator('.mc-recap-story > details')).not.toHaveAttribute('open')
  await page.getByText(/^Earlier moments \(/).click()
  expect(await page.locator('[data-testid="moment-card"]:visible').count()).toBeGreaterThan(6)
  const review = page.getByTestId('moment-card').filter({ hasText: 'Goal disallowed after offside review' })
  await review.getByText('How we know', { exact: true }).click()
  await review.getByRole('group', { name: 'Source events' }).getByRole('button').first().click()
  await expect(page.getByTestId('highlighted-event')).toHaveCount(1)

  await page.getByRole('radio', { name: /Analyst/ }).check()
  await expect(page.getByRole('heading', { name: 'Team metrics' })).toBeVisible()
  await expect(page.locator('.mc-recap-story > details')).toHaveAttribute('open')
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  expect(errors).toEqual([])
})
