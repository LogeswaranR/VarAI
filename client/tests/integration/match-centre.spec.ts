import { expect, test } from '@playwright/test'
import { UI_HOOKS } from '../../src/contracts/ui-hooks'

test('match centre streams a synthetic match, shapes it for three audiences, remembers the choice and hands off to the evidence review', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Match centre', level: 1 })).toBeVisible()
  await expect(page.getByTestId('synthetic-badge')).toContainText('not real data')
  await expect(page.getByLabel('Follow a player').locator('option')).toHaveCount(22)
  await expect(page.getByTestId('scoreline')).toHaveText('0 – 0')
  await expect(page.getByTestId('match-status')).toContainText('Nothing plays until you start it')
  await expect(page.getByTestId('moment-card')).toHaveCount(0)

  await page.getByLabel('Speed').selectOption('600')
  await page.getByRole('button', { name: /67:21 · AVC goal, ruled out on review/ }).click()
  await expect(page.getByTestId('match-status')).toContainText('Full time', { timeout: 30_000 })
  await expect(page.getByTestId('scoreline')).toHaveText('1 – 1')
  await expect(page.getByTestId('lower-third')).toContainText('GOAL · AVC')
  await expect(page.getByTestId('lower-third')).toContainText('AVC 1–1 BRL')

  const disallowed = page.getByTestId('moment-card').filter({ hasText: 'Goal disallowed after offside review' })
  await expect(disallowed).toBeVisible()
  await expect(disallowed).toContainText('AVC 0–0 BRL')
  await expect(disallowed.getByRole('link', { name: /evidence review/ })).toHaveAttribute('href', '/?scenario=S1')
  await expect(page.getByTestId('player-stats')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Team metrics' })).toHaveCount(0)

  await expect(disallowed.getByRole('group', { name: 'Source events' })).toBeHidden()
  await disallowed.getByText('How we know').click()
  await disallowed.getByRole('group', { name: 'Source events' }).getByRole('button').first().click()
  await expect(page.getByTestId('highlighted-event')).toHaveCount(1)

  await page.getByRole('radio', { name: /Analyst/ }).check()
  await expect(page.getByRole('heading', { name: 'Team metrics' })).toBeVisible()
  await expect(page.getByTestId('team-stats')).toContainText('Hardest completed pass')
  await expect(page.getByRole('img', { name: /Control index by minute/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Raw event feed' })).toBeVisible()
  await expect(page.getByText(/\d{4} events received/)).toBeVisible()
  await expect(page.getByTestId('moment-card').filter({ hasText: 'Pass difficulty' }).first()).toBeVisible()

  await page.getByLabel('Favourite club').selectOption('LANTERNS')
  await expect(page.getByLabel('Follow a player')).toHaveValue('LANTERNS-09')
  await page.getByRole('radio', { name: /Studio/ }).check()
  await expect(page.getByRole('heading', { name: 'Studio cue queue' })).toBeVisible()
  expect(await page.getByTestId('cue-row').count()).toBeGreaterThan(15)
  await page.getByRole('button', { name: 'REVIEW · GOAL DISALLOWED' }).click()
  await expect(page.getByTestId('cue-json')).toContainText('"scenarioId": "S1"')
  await expect(page.getByTestId('cue-json')).toContainText('"schemaVersion": "1.0"')
  await expect(page.getByTestId('cue-json')).toContainText('"sourceEventIds"')

  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(1)

  await page.reload()
  await expect(page.getByRole('radio', { name: /Studio/ })).toBeChecked()
  await expect(page.getByLabel('Favourite club')).toHaveValue('LANTERNS')

  await page.getByRole('radio', { name: /Fan/ }).check()
  const review = page.getByTestId('moment-card')
  await expect(review).toHaveCount(0)
  await page.getByLabel('Speed').selectOption('600')
  await page.getByRole('button', { name: /67:21 · AVC goal, ruled out on review/ }).click()
  await expect(page.getByTestId('match-status')).toContainText('Full time', { timeout: 30_000 })
  await page.getByTestId('moment-card').filter({ hasText: 'Goal disallowed after offside review' })
    .getByRole('link', { name: /evidence review/ }).click()
  await expect(page.getByRole('heading', { name: 'Review room', level: 1 })).toBeVisible()
  await expect(page.getByTestId(UI_HOOKS.scenarioSelect)).toHaveValue('S1')
})

test('the raw, overlay and combined endpoints expose the same match for other consumers', async ({ request }) => {
  const description = await (await request.get('/api/matches/SYN-MATCH-01')).json()
  expect(description.synthetic).toBe(true)
  expect(description.highlights).toHaveLength(3)

  const overlays = await request.get('/api/matches/SYN-MATCH-01/overlays?speed=1000&fromSeconds=5000')
  expect(overlays.headers()['content-type']).toContain('text/event-stream')
  const text = await overlays.text()
  const messages = text.split('\n\n').filter(Boolean).map(block => JSON.parse(block.split('\n').find(line => line.startsWith('data: '))!.slice(6)))
  expect(messages[0].type).toBe('match')
  expect(messages.at(-1).type).toBe('complete')
  const cues = messages.filter(message => message.type === 'overlay').map(message => message.payload)
  expect(cues.length).toBe(messages.at(-1).payload.overlayCount)
  expect(cues.every(cue => cue.schemaVersion === '1.0' && cue.sourceEventIds.length > 0 && cue.outMs > cue.inMs)).toBe(true)
  expect(cues.some(cue => cue.kind === 'GOAL_DISALLOWED' && cue.scenarioId === 'S1')).toBe(true)

  expect((await request.get('/api/matches/SYN-MATCH-01/events?speed=0')).status()).toBe(400)
  expect((await request.get('/api/matches/OTHER/stream')).status()).toBe(404)
})
